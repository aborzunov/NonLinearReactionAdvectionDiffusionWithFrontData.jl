# Тест для минимизации функционала
#
# Проверяет, что функционал J убывает вдоль итераций градиентного спуска.
#
# Это интеграционный тест всего pipeline:
# прямая задача → сопряжённая задача → градиент → шаг спуска.
#
# Если хотя бы одна из компонент pipeline некорректна (например, неправильный
# знак градиента или ошибка в шаге спуска), функционал не будет убывать.

using NonLinearReactionAdvectionDiffusionWithFrontData
using Test

@testset "Функционал убывает при минимизации" begin

    a, b, t₀, T, N, M, ε, Xₙ, Tₘ, qₙ, ulₘ, urₘ, u₀ = dparams()

    # Генерируем наблюдения от истинного q
    u_true, _, _ = solve(u₀, Xₙ, N, Tₘ, M, ε, ulₘ, urₘ, qₙ)
    _, _, _, f1_data, f2_data = generate_obs_data(u_true, Xₙ, N, Tₘ, M, qₙ, ulₘ, urₘ)

    # Запускаем минимизацию с нулевым начальным приближением (заведомо далёким от истины)
    q₀ = zeros(N+1)
    _, Js, _ = minimize(q₀, u₀, ulₘ, urₘ, Xₙ, N, Tₘ, M, ε, f1_data, f2_data;
                        S = 5, β = 0.01, w = 0.0005)

    # Функционал должен убывать на каждом шаге
    @test all(diff(Js) .< 0)

end
